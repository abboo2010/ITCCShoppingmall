"""Detect shop-lot outlines on the floor plan images and write lots.js.

Usage (from the repo root):  python3 tools/detect_lots.py
Needs: pip install opencv-python-headless numpy

Output: lots.js  ->  window.ITCC_PLAN = { g|1|2|3: { w, h, lots: [{id,x,y,w,h}] } }
The ids (G-001, 1-001 ...) are internal hotspot ids, assigned in reading order.
Shop names / phone numbers live in lot-shops.js, keyed by these ids.
Re-run this whenever the floor plan images in images/ are replaced.
NOTE: re-running changes ids, so re-map lot-shops.js afterwards.
"""
import cv2, json, numpy as np

FLOORS = [("g", "ground-floor", "G"), ("1", "first-floor", "1"),
          ("2", "second-floor", "2"), ("3", "third-floor", "3")]

def detect(path, d=10, hk=18, vk=14):
    img = cv2.imread(path); H, W = img.shape[:2]
    gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
    bg = cv2.medianBlur(gray, 25)
    dk = ((bg.astype(int) - gray.astype(int)) > d).astype(np.uint8)
    hl = cv2.morphologyEx(dk, cv2.MORPH_OPEN, cv2.getStructuringElement(cv2.MORPH_RECT, (hk, 1)))
    vl = cv2.morphologyEx(dk, cv2.MORPH_OPEN, cv2.getStructuringElement(cv2.MORPH_RECT, (1, vk)))
    lines = cv2.dilate(hl | vl, np.ones((3, 3), np.uint8))
    n, lab, st, _ = cv2.connectedComponentsWithStats((1 - lines).astype(np.uint8), connectivity=4)
    hsv = cv2.cvtColor(img, cv2.COLOR_BGR2HSV)
    out = []
    for i in range(1, n):
        x, y, w, h, a = st[i]
        if not (16 <= w <= 140 and 14 <= h <= 110 and a >= 250): continue
        if a / (w * h) < 0.72: continue
        m = lab[y:y+h, x:x+w] == i
        sat = hsv[y:y+h, x:x+w, 1][m].mean(); hue = hsv[y:y+h, x:x+w, 0][m].mean()
        if not (28 < sat <= 140 and 14 <= hue <= 34 and not (hue > 27 and sat > 100)): continue
        if dk[y:y+h, x:x+w][m].mean() > 0.30: continue
        out.append((int(x), int(y), int(w), int(h)))
    out.sort(key=lambda r: (round(r[1] / 20), r[0]))
    return out, (W, H)

plan = {}
for key, name, prefix in FLOORS:
    cells, (W, H) = detect(f"images/{name}.png")
    plan[key] = {"w": W, "h": H, "lots": [
        {"id": f"{prefix}-{i+1:03d}", "x": x, "y": y, "w": w, "h": h}
        for i, (x, y, w, h) in enumerate(cells)]}
    print(name, len(cells), "lots")

with open("lots.js", "w", encoding="utf-8") as f:
    f.write("// AUTO-GENERATED by tools/detect_lots.py - shop lot outlines on each floor plan image.\n")
    f.write("window.ITCC_PLAN = " + json.dumps(plan, separators=(",", ":")) + ";\n")
